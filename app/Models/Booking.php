<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

class Booking extends Model
{
    use HasFactory;

    protected $fillable = [
        'plot_id',
        'user_id',
        'referral_agent_id',
        'additional_info',
        'price',
        'booking_payment',
        'custom_booking_amount',
        'remaining_payment',
        'installment_plan',
        'total_installments',
        'installment_payment',
        'status',
        'booking_date',
        'pre_booking_expires_at',
        'agent_changed_at',
        'agent_commission_base_paid',
        'agent_commission',
        'commission_scheme',
        'owners',
    ];

    protected $casts = [
        'price' => 'decimal:2',
        'booking_payment' => 'decimal:2',
        'custom_booking_amount' => 'decimal:2',
        'remaining_payment' => 'decimal:2',
        'installment_payment' => 'decimal:2',
        'booking_date' => 'datetime',
        'pre_booking_expires_at' => 'datetime',
        'agent_changed_at' => 'datetime',
        'agent_commission_base_paid' => 'decimal:2',
        'agent_commission' => 'decimal:2',
        'owners' => 'array',
    ];

    /**
     * Check if this is a pre-booked booking.
     */
    public function isPreBooked(): bool
    {
        return $this->status === 'pre-booked';
    }

    /**
     * Check if the pre-booking has expired.
     */
    public function isPreBookingExpired(): bool
    {
        return $this->isPreBooked() && $this->pre_booking_expires_at && $this->pre_booking_expires_at->isPast();
    }

    /**
     * Get the display booking amount (custom or full).
     */
    public function getDisplayBookingAmountAttribute(): string
    {
        if ($this->custom_booking_amount) {
            return $this->custom_booking_amount;
        }
        return $this->booking_payment;
    }

    /**
     * Adjusted installment = outstanding balance / remaining installments.
     *
     * Mirrors the calculation used by the payment & invoice controllers so the
     * "real" per-installment figure can be shown anywhere a booking is rendered.
     * Requires the payments relation to be loaded; otherwise falls back to the
     * original (configured) installment amount.
     */
    public function getAdjustedInstallmentAttribute(): float
    {
        $original = (float) $this->installment_payment;

        if (! $this->relationLoaded('payments') || ! $this->total_installments) {
            return $original;
        }

        $totalPaid = (float) $this->payments->sum('amount');
        $paidInstallments = (int) $this->payments
            ->whereIn('payment_type', ['Installment Payment', 'Part Of Installment'])
            ->sum('instalment_quantity');

        $remainingInstallments = max(0, ((int) $this->total_installments) - $paidInstallments);
        if ($remainingInstallments <= 0) {
            return $original;
        }

        $outstanding = (float) $this->price - $totalPaid;

        return round($outstanding / $remainingInstallments, 2);
    }

    /**
     * Get the plot for this booking.
     */
    public function plot()
    {
        return $this->belongsTo(Plot::class);
    }

    /**
     * Get the user (customer) for this booking.
     */
    public function user()
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Get the agent by referral agent ID.
     */
    public function agent()
    {
        return $this->belongsTo(User::class, 'referral_agent_id');
    }

    /**
     * The commission user who made this sale (alias of agent()).
     */
    public function seller()
    {
        return $this->belongsTo(User::class, 'referral_agent_id');
    }

    /**
     * Legacy bookings use the old flat agent_commission rate.
     */
    public function isFlatScheme(): bool
    {
        return $this->commission_scheme !== 'hierarchy';
    }

    /**
     * New bookings distribute commission per the hierarchy chart.
     */
    public function isHierarchyScheme(): bool
    {
        return $this->commission_scheme === 'hierarchy';
    }

    /**
     * Commission ledger rows generated by this booking's payments.
     */
    public function commissionEarnings()
    {
        return $this->hasMany(CommissionEarning::class);
    }

    /**
     * Get all payments for this booking.
     */
    public function payments()
    {
        return $this->hasMany(Payment::class);
    }
}
